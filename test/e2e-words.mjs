import { chromium } from '@playwright/test';
import fs from 'node:fs';
const BASE = process.env.BASE || 'http://localhost:4173/';
const OUT = process.env.OUT || 'shots-words';
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const errs = [];
async function run(viewport, mobile) {
  const ctx = await browser.newContext({ viewport, deviceScaleFactor: mobile ? 2 : 1, isMobile: mobile, hasTouch: mobile });
  const page = await ctx.newPage();
  page.on('pageerror', (e) => errs.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  await page.goto(BASE + '?user=Arunabh-pandey&game=186131916376');
  await page.waitForSelector('.progress.complete', { timeout: 600000 });
  await page.evaluate(() => window.__review.go(26));
  await page.waitForTimeout(400);
  return { ctx, page };
}
const { page } = await run({ width: 1400, height: 950 }, false);
const card = () => page.locator('#movecard').innerText();
console.log('--- 13...Nc2+ (words) ---\n' + (await card()));
console.log('graph caption:', await page.locator('.graph-cap').innerText());
await page.locator('#mc-more summary').click();
await page.locator('.info').hover();
await page.waitForTimeout(200);
console.log('tip:', await page.locator('.info').getAttribute('data-tip'));
await page.screenshot({ path: `${OUT}/desktop-Nc2-words.png` });
await page.locator('#nt-toggle').click();
await page.waitForTimeout(200);
console.log('--- notation mode ---\n' + (await card()));
await page.screenshot({ path: `${OUT}/desktop-Nc2-notation.png` });
await page.locator('#nt-toggle').click();
await page.evaluate(() => window.__review.go(25));
await page.waitForTimeout(300);
console.log('--- 13.c3 ---\n' + (await card()));
await page.evaluate(() => window.__review.go(55));
await page.waitForTimeout(300);
console.log('--- 28.Bf6 ---\n' + (await card()));
const m = await run({ width: 390, height: 844 }, true);
const ow = await m.page.evaluate(() => document.documentElement.scrollWidth);
console.log('mobile scrollWidth:', ow);
await m.page.locator('#movecard').scrollIntoViewIfNeeded();
await m.page.screenshot({ path: `${OUT}/mobile-Nc2.png`, fullPage: true });
await m.page.locator('#movecard').screenshot({ path: `${OUT}/mobile-Nc2-card.png` });
console.log('errors:', errs.length ? errs.join(' | ') : 'none');
await browser.close();
